const {chromium}=require('playwright');
const fs=require('fs');
const path=require('path');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.HS_CHROMIUM_PATH||undefined,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const requests=[];
 const state={features:{host_usage_ratio:{enabled:true},node_pro:{enabled:true}},hosts:[{id:1,remark:'Host 1'}]};
 const shield={status:{mode:'observe',stage:'normal',updated_at:new Date().toISOString(),enforcement:{active:false},metrics:{pps:12,mbps:2},layers:{}},config:{enabled:true,auto_stage:true,mode:'observe',policy:{management_ports:[22],rules:[],syn_ports:[],syn_rate:100}},events:[]};
 const inventory={targets:[{id:'panel',name:'Main panel',online:true,certificates:[{id:'example.com',domains:['example.com'],provider:'certbot',renewable:true,expires_at:Date.now()/1000+86400*20,starts_at:Date.now()/1000-86400*70}],proxies:[]}],node_trust:[],jobs:[]};
 await page.route('http://hs.test/**',async route=>{
  const url=new URL(route.request().url());let data={};requests.push(url.pathname);
  if(url.pathname==='/api/hs-plugin/state')data=state;
  else if(url.pathname==='/api/hs-shield/status')data=shield;
  else if(url.pathname==='/api/hs-services/inventory')data=inventory;
  else if(url.pathname==='/api/cores')data={cores:[]};
  else if(url.pathname==='/api/hs-services/fair-use')data={policies:{},blocker:'Rate adapter required'};
  else if(url.pathname==='/api/hs-shield/config'){const body=route.request().postDataJSON();Object.assign(shield.config,body);data={ok:true};}
  else if(!url.pathname.startsWith('/api/'))return route.fulfill({contentType:'text/html',body:'<!doctype html><html><head></head><body><aside><ul><li><a href="/nodes" data-sidebar="menu-button">Nodes</a></li></ul></aside><main class="dashboard-scroll"><div class="flex min-h-0 w-full flex-1 flex-col justify-between"><div class="flex min-h-0 flex-1 flex-col"><div id="native-page">Native page</div></div><footer>PasarGuard</footer></div></main></body></html>'});
  await route.fulfill({contentType:'application/json',body:JSON.stringify(data)});
 });
 await page.goto('http://hs.test/nodes');
 await page.evaluate(()=>localStorage.setItem('token','test-token'));
 for(const file of ['hs-plugin.js','hs-tab-fix.js','hs-shield.js','hs-services.js'])await page.addScriptTag({content:fs.readFileSync(path.join(__dirname,'../plugin',file),'utf8')});
 await page.waitForSelector('#hs-plugin-nav');
 const menu=page.locator('#hs-plugin-submenu');const arrow=page.locator('.hs-plugin-menu-action');
 assert.equal(await menu.isVisible(),false);
 await arrow.click();assert.equal(await menu.isVisible(),true);
 await arrow.click();assert.equal(await menu.isVisible(),false);
 await page.locator('[data-hs-parent]').click();await page.waitForSelector('#hs-plugin-root');
 assert.equal(await page.locator('#hs-plugin-top-tabs [data-service-tab=firewall]').isVisible(),true);
 await page.locator('#hs-plugin-top-tabs [data-service-tab=firewall]').click();await page.waitForSelector('#hs-shield-root');
 assert.equal(await page.locator('#hs-plugin-root').count(),0);
 await page.locator('[data-shield-section=rules]').click();
 await page.locator('input[name=source]').fill('192.0.2.0/24');
 await page.evaluate(()=>window.HSShieldDebug.refresh());
 assert.equal(await page.locator('input[name=source]').inputValue(),'192.0.2.0/24');
 await page.locator('[data-add] button').click();
 await page.waitForSelector('[data-remove]');
 await Promise.all([page.waitForResponse(r=>r.url().endsWith('/api/hs-shield/config')),page.locator('[data-save]').click()]);
 assert.equal(shield.config.policy.rules[0].source,'192.0.2.0/24');
 await page.locator('[data-service-tab=certificates]').click();await page.waitForSelector('[data-renew]');
 assert.equal(await page.locator('#hs-shield-root').count(),0);
 assert.equal(await page.locator('[data-renew]').isEnabled(),true);
 await Promise.all([page.waitForResponse(r=>r.url().endsWith('/api/hs-services/targets/panel/renew')),page.locator('[data-renew]').click()]);assert(requests.includes('/api/hs-services/targets/panel/renew'));
 await page.locator('[data-service-tab=features]').click();await page.waitForSelector('#hs-plugin-root');
 assert.equal(await page.locator('#hs-services-root').count(),0);
 await page.locator('[data-hs-parent]').click();
 await arrow.click();
 if(!(await menu.isVisible()))await arrow.click();
 await page.locator('[data-hs-sub=firewall]').click();await page.waitForSelector('#hs-shield-root');
 await page.locator('[data-service-tab=fair]').click();await page.waitForSelector('[data-preview-user]');
 await page.locator('[data-service-tab=mtproxy]').click();await page.waitForSelector('input[name=metrics_port]');
 await page.locator('a[href="/nodes"]').click();
 assert.equal(await page.locator('#hs-services-root').count(),0);
 assert.equal(await page.locator('#native-page').isVisible(),true);
 assert.deepEqual(errors,[]);
 console.log('UI navigation: arrow, top tabs, forms, renewal, sidebar, native restore passed');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
